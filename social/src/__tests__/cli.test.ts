describe('chooseBed — deterministic for a given date+slot', () => {
	it('the same postIndex always chooses the same bed', () => {
		const seed = postIndexForSlot('2026-09-01', 1);
		expect(chooseBed(seed).id).toBe(chooseBed(seed).id);
	});

	it('a different (date, slot) pair usually chooses a different postIndex, and consecutive slots never repeat a bed', () => {
		const seedSlot1 = postIndexForSlot('2026-09-01', 1);
		const seedSlot2 = postIndexForSlot('2026-09-01', 2);
		expect(seedSlot2).toBe(seedSlot1 + 1);
		expect(chooseBed(seedSlot1).id).not.toBe(chooseBed(seedSlot2).id);
	});
});

