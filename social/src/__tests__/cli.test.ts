const moduleDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(moduleDir, '..', '..', '..');
const cliPath = path.join(repoRoot, 'social', 'src', 'cli.ts');
const scheduleDir = path.join(repoRoot, 'content', 'social');

// --- Real, committed week-1 schedule (generated by
// `npx tsx scripts/generate-schedule.ts --week 1 --seed 42 --first-week`) ---
const WEEK_1_SCHEDULE = JSON.parse(
	readFileSync(path.join(scheduleDir, scheduleFileName(1)), 'utf-8')
) as WeekSchedule;

interface RunResult {
	status: number;
	stdout: string;
	stderr: string;
}

function runCli(args: string[]): RunResult {
	try {
		const stdout = execFileSync('npx', ['tsx', cliPath, ...args], {
			cwd: repoRoot,
			encoding: 'utf-8',
			stdio: ['ignore', 'pipe', 'pipe']
		});
		return { status: 0, stdout, stderr: '' };
	} catch (e) {
		const err = e as { status: number | null; stdout: string; stderr: string };
		return { status: err.status ?? 1, stdout: err.stdout ?? '', stderr: err.stderr ?? '' };
	}
}

