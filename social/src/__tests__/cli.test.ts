describe('--dry-run', () => {
	// `outDir` is a nonexistent `out` child of `parentDir` — dry-run never
	// creates it (that's the point of the test), so removing `outDir` alone
	// is a no-op. Track and remove the mkdtemp parent instead, or it leaks.
	let parentDir: string;
	let outDir: string;

	afterEach(async () => {
		if (parentDir) await rm(parentDir, { recursive: true, force: true });
	});

	it('prints the plan and writes nothing', async () => {
		parentDir = await mkdtemp(path.join(tmpdir(), 'plain-social-cli-dry-'));
		outDir = path.join(parentDir, 'out');

		const result = runCli(['render', '--date', '2026-09-01', '--slot', '1', '--out', outDir, '--dry-run']);
		expect(result.status).toBe(0);
		expect(result.stdout).toMatch(/meditations-02-001/);
		// Day 1's read-through card (meditations-02-001) is a genuine Wall
		// slot under the real committed week-1 schedule — see the
		// `resolveSlot` describe block above.
		expect(result.stdout).toMatch(/composition: Wall/);
		expect(result.stdout.toLowerCase()).toMatch(/dry run/);
		expect(existsSync(outDir)).toBe(false);
	});

	// Pf39c2-social-pilot-02a D01: this used to also dry-run a Still slot
	// (day 2, meditations-02-002, whose plain_english has no qualifying
	// landing line) to prove the framing layer's Still branch. Still was
	// deleted outright — the committed week-1 schedule still carries that
	// slot's format as `"still"` until D04 regenerates it, and rendering it
	// now throws (see `buildRenderPlan`'s deprecation branch in `cli.ts`),
	// so there is no "prints the plan" case left to assert for it.
});

