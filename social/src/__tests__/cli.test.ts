describe('render — end-to-end: a real MP4, IG feed still, and metadata sidecar', () => {
	let outDir: string;

	afterEach(async () => {
		if (outDir) await rm(outDir, { recursive: true, force: true });
	});

	it(
		// social pilot 02a V17 (2026-08-27, user decision): the 15s floor is
		// gone — duration is now a pure function of screen count and can land
		// well under 15s (this real day-6 card renders ~8.5s). Only the 59s
		// ceiling remains.
		'produces a house-profile-conformant MP4 (<=59s), an IG feed JPEG, and a metadata sidecar with narration: false',
		async () => {
			// Day 6 of the REAL committed week-1 schedule (discourses-53-019) —
			// a real Wall slot.
			const slot = resolveDay(WEEK_1_SCHEDULE, 6);
			if (slot.content.format !== 'wall') throw new Error('expected a wall slot');

			const date = weekDayToDate(1, 6);
			outDir = await mkdtemp(path.join(tmpdir(), 'plain-social-cli-e2e-'));

			const result = runCli(['render', '--date', date, '--out', outDir]);
			expect(result.status).toBe(0);

			const videoPath = path.join(outDir, `wall-${date}.mp4`);
			const feedPath = path.join(outDir, `wall-${date}-feed.jpg`);
			const metadataPath = path.join(outDir, `wall-${date}.json`);

			expect(existsSync(videoPath)).toBe(true);
			expect(existsSync(feedPath)).toBe(true);
			expect(existsSync(metadataPath)).toBe(true);

			const probeResult = await probe(videoPath);
			expect(() => assertMeetsProfile(probeResult)).not.toThrow();
			// No floor (V17) — only the 59s ceiling is enforced.
			expect(probeResult.durationSec ?? 0).toBeGreaterThan(0);
			expect(probeResult.durationSec ?? 0).toBeLessThanOrEqual(59);

			const metadata = JSON.parse(readFileSync(metadataPath, 'utf-8'));
			expect(metadata.card_id).toBe(slot.card_id);
			expect(metadata.format).toBe('wall');
			expect(metadata.narration).toBe(false);
			expect(metadata.rendered_at).toBe(`${date}T00:00:00.000Z`);
			// T17 retired the opening rotation entirely — the sidecar carries
			// no opening field at all, for any format.
			expect(metadata.opening).toBeUndefined();
			// Pf39c2-social-pilot-02a D02: the read-through/two-slot day is gone
			// — no `slot` field on the sidecar any more.
			expect(metadata.slot).toBeUndefined();

			const feedBuf = readFileSync(feedPath);
			// JPEG magic bytes.
			expect(feedBuf.subarray(0, 2).toString('hex')).toBe('ffd8');
		},
		300_000
	);
});

